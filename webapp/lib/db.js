import { DatabaseSync } from 'node:sqlite';
import { mkdirSync } from 'node:fs';
import { dirname } from 'node:path';

/** Opens (and migrates) the SQLite database. ':memory:' is used by the tests. */
export function openDb(file) {
  if (file !== ':memory:') mkdirSync(dirname(file), { recursive: true });
  const db = new DatabaseSync(file);
  db.exec('PRAGMA journal_mode = WAL; PRAGMA foreign_keys = ON; PRAGMA busy_timeout = 5000;');
  db.exec(`
    CREATE TABLE IF NOT EXISTS users (
      id          TEXT PRIMARY KEY,
      email       TEXT NOT NULL UNIQUE,
      name        TEXT NOT NULL DEFAULT '',
      pass_hash   TEXT NOT NULL,
      role        TEXT NOT NULL DEFAULT 'user',
      session_ver INTEGER NOT NULL DEFAULT 1,
      disabled    INTEGER NOT NULL DEFAULT 0,
      created_at  INTEGER NOT NULL
    );
    CREATE TABLE IF NOT EXISTS devices (
      id           TEXT PRIMARY KEY,           -- generated by the car app (uuid)
      key_hash     TEXT NOT NULL,              -- sha256 of the device key (the key never leaves the car after registration)
      owner_id     TEXT REFERENCES users(id) ON DELETE SET NULL,
      vin          TEXT,                       -- VIN declared by the owner at claim time
      reported_vin TEXT,                       -- VIN the car itself reported (telemetry / registration)
      name         TEXT NOT NULL DEFAULT '',
      app_version  TEXT,
      created_at   INTEGER NOT NULL,
      claimed_at   INTEGER,
      last_seen    INTEGER
    );
    -- A chassis can belong to exactly one account at a time.
    CREATE UNIQUE INDEX IF NOT EXISTS devices_vin_claimed ON devices(vin) WHERE vin IS NOT NULL AND owner_id IS NOT NULL;
    CREATE INDEX IF NOT EXISTS devices_owner ON devices(owner_id);
    CREATE TABLE IF NOT EXISTS pairings (
      code       TEXT PRIMARY KEY,
      device_id  TEXT NOT NULL REFERENCES devices(id) ON DELETE CASCADE,
      expires_at INTEGER NOT NULL
    );
    CREATE TABLE IF NOT EXISTS audit (
      id INTEGER PRIMARY KEY AUTOINCREMENT, t INTEGER NOT NULL, user_id TEXT, device_id TEXT, event TEXT NOT NULL, detail TEXT
    );
  `);
  return db;
}
